#include <iostream>
using namespace std;
int main () {
       // relational operator
       int a = 5;
       int b = 7;
    cout<<(a==b)<<endl;
    cout<<(a<b)<<endl;
    cout<<(a>b)<<endl;
    cout<<(a<=b)<<endl;
    cout<<(a>=b)<<endl;
    cout<<(a!=b)<<endl;
    // these are relational operator: ==,!=, <, >, <=, >=.
    // and these operator gives straight results eithe true or 
    // false 
    // and these true false value are bool data type 
    // prints 0 if false ptint 1 if true.
}
